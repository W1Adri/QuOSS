class TestAzimuthWraps:
    """Azimuth is always in [0, 2 pi), including for satellites due north or south."""

    @pytest.mark.physics
    @pytest.mark.parametrize("raan_offset_deg", [0.0, 45.0, 90.0, 135.0, 180.0, 270.0, 359.0])
    def test_wraps(self, raan_offset_deg: float) -> None:
        coe = _sso_700km(
            raan_rad=CASTELLDEFELS_LON_RAD + np.deg2rad(raan_offset_deg),
            true_anomaly_rad=0.0,
        )
        traj = _propagate_orbit(coe, span_s=6000.0, n_samples=200)
        angles = look_angles(
            traj, CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )
        assert np.all(angles.azimuth_rad >= 0.0)
        assert np.all(angles.azimuth_rad < 2.0 * np.pi)


class TestRangeEqualsVectorNorm:
    """range_km is exactly the norm the ENU components (elevation/azimuth/range) imply.

    ``range * (cos(el) sin(az), cos(el) cos(az), sin(el))`` reconstructs the
    ENU vector this module computed internally; if ``range_km`` disagreed with
    that vector's own norm, the reconstruction would not close — a stronger
    check than trusting ``range_km`` in isolation.
    """

    @pytest.mark.physics
    def test_reconstruction(self) -> None:
        coe = _sso_700km(raan_rad=np.deg2rad(15.0), true_anomaly_rad=np.deg2rad(200.0))
        traj = _propagate_orbit(coe, span_s=3000.0, n_samples=70)
        angles = look_angles(
            traj, CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )
        east = angles.range_km * np.cos(angles.elevation_rad) * np.sin(angles.azimuth_rad)
        north = angles.range_km * np.cos(angles.elevation_rad) * np.cos(angles.azimuth_rad)
        up = angles.range_km * np.sin(angles.elevation_rad)
        reconstructed_range = np.sqrt(east**2 + north**2 + up**2)
        np.testing.assert_allclose(reconstructed_range, angles.range_km, rtol=1e-12)


class TestRangeRateMatchesFiniteDifference:
    """range_rate_km_s agrees with a central finite difference of range_km itself.

    This does not validate the *physics* (both sides come from this module's
    own rotation of the same trajectory) — it validates that the analytic
    range-rate formula (projecting relative velocity onto the line of sight)
    really is the derivative of the range this module also reports, catching a
    sign error or a dropped term that a shape or wrap-range check would not.
    """

    @pytest.mark.physics
    def test_matches_derivative(self) -> None:
        coe = _sso_700km(raan_rad=np.deg2rad(15.0), true_anomaly_rad=np.deg2rad(200.0))
        step_s = 0.05
        grid = TimeGrid.uniform(epoch_jd=2460676.5, duration_s=2 * step_s, n=3)
        traj = propagate(coe, grid, method=PropagationMethod.TWO_BODY)
        angles = look_angles(
            traj, CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )
        finite_difference = (angles.range_km[0, 2] - angles.range_km[0, 0]) / (2 * step_s)
        # abs=1e-3 km/s, not 1e-6: a central difference has O(step_s^2) truncation
        # error, and at step_s=0.05 s on a curved range-vs-time trajectory the
        # residual measured here is ~4.4e-4 km/s — this bound catches a sign
        # error or a dropped term (which would be orders of magnitude larger),
        # not that truncation error.
        assert angles.range_rate_km_s[0, 1] == pytest.approx(finite_difference, abs=1e-3)


class TestPointAheadAngleZeroForRadialMotion:
    """A satellite moving straight along the line of sight needs no lead-ahead.

    Built directly in ITRF, where "radial" is exact: a point on the station's
    zenith radial, moving further along that same radial, so the transverse
    component the point-ahead angle depends on is exactly zero, not just small.
    """

    @pytest.mark.physics
    def test_pure_radial(self) -> None:
        zenith_direction = geodetic_to_itrf(CASTELLDEFELS_LAT_RAD, 0.0, 0.0)[0]
        zenith_direction = zenith_direction / np.linalg.norm(zenith_direction)
        r_itrf = zenith_direction * (WGS84_RADIUS_EQUATORIAL_KM + 700.0)
        v_itrf = zenith_direction * 1.0  # 1 km/s, straight up
        traj = _trajectory_from_itrf_state(r_itrf, v_itrf, epoch_jd=2451545.0)
        angles = look_angles(traj, CASTELLDEFELS_LAT_RAD, 0.0, 0.0)
        assert angles.point_ahead_angle_rad[0, 0] == pytest.approx(0.0, abs=1e-10)
        assert angles.range_rate_km_s[0, 0] == pytest.approx(1.0, abs=1e-10)


class TestPointAheadAngleFormula:
    """point_ahead_angle_rad matches ``2 * v_perp / c`` for a hand-built geometry.

    Satellite due east of an equatorial station, moving purely north —
    perpendicular to the station-to-satellite line of sight, which points
    along local east. Every metre per second of that velocity is transverse,
    so the point-ahead angle is exactly ``2 * speed / c`` with nothing to
    project out, and the range-rate is exactly zero.
    """

    @pytest.mark.physics
    def test_purely_transverse(self) -> None:
        station_r = geodetic_to_itrf(0.0, 0.0, 0.0)[0]
        offset_km = 500.0
        speed_km_s = 3.0
        r_itrf = station_r + np.array([0.0, offset_km, 0.0])  # +y is local east here
        v_itrf = np.array([0.0, 0.0, speed_km_s])  # +z is north
        traj = _trajectory_from_itrf_state(r_itrf, v_itrf, epoch_jd=2451545.0)
        angles = look_angles(traj, 0.0, 0.0, 0.0)
        expected = 2.0 * speed_km_s * 1000.0 / SPEED_OF_LIGHT_M_S
        assert angles.point_ahead_angle_rad[0, 0] == pytest.approx(expected, rel=1e-10)
        assert angles.range_rate_km_s[0, 0] == pytest.approx(0.0, abs=1e-9)


class TestPointAheadAngle:
    """The measured example the module docstring cites.

    Finds the highest-elevation sample over one pass of the 700 km SSO used
    throughout this repo — chosen, by a coarse day-long search recorded here
    rather than repeated in every test run, to bring the satellite to 67 deg
    over Castelldefels — and reports the point-ahead angle there. This is the
    test the module docstring's "Measured, not asserted" paragraph names — if
    the asserted values below ever need to change, that paragraph must be
    updated to match, never the other way around.

    The window searched is ``t_s`` in ``[21300, 21600)`` from the same epoch
    and elements as :func:`_sso_700km` with ``raan_rad=CASTELLDEFELS_LON_RAD``
    and ``true_anomaly_rad=275 deg``: a coarse scan of the whole sidereal day
    at 10 s resolution found the closest approach near ``t_s = 21441 s``, and
    this test resamples only that 300 s window at 0.1 s resolution rather than
    paying for day-long, sub-second sampling on every run.
    """

    @pytest.mark.physics
    def test_measured_example(self) -> None:
        coe = _sso_700km(raan_rad=CASTELLDEFELS_LON_RAD, true_anomaly_rad=np.deg2rad(275.0))
        grid = TimeGrid(epoch_jd=2460676.5, t_s=np.arange(21_300.0, 21_600.0, 0.1))
        traj = propagate(coe, grid, method=PropagationMethod.TWO_BODY)
        angles = look_angles(
            traj, CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )
        closest_idx = int(np.argmax(angles.elevation_rad[0]))
        max_elevation_deg = float(np.rad2deg(angles.elevation_rad[0, closest_idx]))
        paa_urad = float(angles.point_ahead_angle_rad[0, closest_idx]) * 1e6
        assert max_elevation_deg == pytest.approx(67.13, abs=0.05)
        assert paa_urad == pytest.approx(50.58, abs=0.05)


