class TestZenithIsElevationNinety:
    """A satellite placed exactly on the station's zenith normal reads elevation 90.

    Built directly in ITRF via :func:`_up_unit_vector`, not from an orbit: the
    satellite is put at the station's own position plus 700 km along the exact
    normal :func:`~quoss.orbits.frames.enu_from_itrf` uses as "up", so
    elevation 90 deg and range 700 km both hold to floating-point precision,
    not just approximately.
    """

    @pytest.mark.physics
    def test_zenith(self) -> None:
        up = _up_unit_vector(CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD)
        station_r = geodetic_to_itrf(
            CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )[0]
        r_itrf = station_r + up * 700.0
        traj = _trajectory_from_itrf_state(r_itrf, np.zeros(3), epoch_jd=2460676.5)
        angles = look_angles(
            traj, CASTELLDEFELS_LAT_RAD, CASTELLDEFELS_LON_RAD, CASTELLDEFELS_ALT_KM
        )
        assert angles.elevation_rad[0, 0] == pytest.approx(np.pi / 2, abs=1e-9)
        assert angles.range_km[0, 0] == pytest.approx(700.0, abs=1e-9)


