@pytest.mark.skipif(
    not REFERENCE_PATH.exists(),
    reason="geometry_reference.json not generated; see tests/golden/README.md",
)
@pytest.mark.physics
@pytest.mark.reference
class TestAgainstAstropyAltAz:
    """Elevation, azimuth and range against astropy's independent AltAz reduction.

    See ``tests/golden/generators/gen_geometry_reference.py`` for how the
    reference values were produced. Frozen, per ``tests/golden/README.md``:
    CI never regenerates this file, only reads it.
    """

    def test_reference_file_has_a_manifest(self, reference: dict[str, Any]) -> None:
        manifest = reference["manifest"]
        assert manifest["versions"]["astropy"]
        assert manifest["generator"].endswith("gen_geometry_reference.py")

    def test_elevation_azimuth_range_match_astropy(self, reference: dict[str, Any]) -> None:
        worst_elevation_deg = 0.0
        worst_azimuth_deg = 0.0
        worst_range_rel = 0.0
        for case in reference["look_angles"]:
            grid = TimeGrid.uniform(epoch_jd=case["jd_utc"], duration_s=1.0, n=2)
            r_teme = np.tile(np.array(case["r_teme_km"]), (2, 1))
            v_teme = np.tile(np.array(case["v_teme_km_s"]), (2, 1))
            traj = Trajectory(
                r_km=r_teme[np.newaxis, :, :],
                v_km_s=v_teme[np.newaxis, :, :],
                grid=grid,
                frame=Frame.TEME,
                method=PropagationMethod.TWO_BODY,
            )
            angles = look_angles(
                traj,
                np.deg2rad(case["station_latitude_deg"]),
                np.deg2rad(case["station_longitude_deg"]),
                case["station_altitude_km"],
            )
            el_deg = float(np.rad2deg(angles.elevation_rad[0, 0]))
            az_deg = float(np.rad2deg(angles.azimuth_rad[0, 0])) % 360.0
            range_km = float(angles.range_km[0, 0])

            worst_elevation_deg = max(
                worst_elevation_deg, abs(el_deg - case["elevation_astropy_deg"])
            )
            az_diff = (az_deg - case["azimuth_astropy_deg"] + 180.0) % 360.0 - 180.0
            worst_azimuth_deg = max(worst_azimuth_deg, abs(az_diff))
            worst_range_rel = max(
                worst_range_rel,
                abs(range_km - case["range_astropy_km"]) / case["range_astropy_km"],
            )

        # Bounds set from what this comparison actually measures, with margin
        # — not from the frame error budget alone, which sets the right order
        # of magnitude (quoss.orbits.frames' module docstring: ~14 m of
        # polar-motion residual and up to ~460 m from UT1~UTC at LEO range,
        # both well under a kilometre) but not the exact figure, because this
        # comparison also carries astropy's own AltAz refraction-model
        # bookkeeping and the two independent ellipsoid implementations. The
        # worst case measured across these 24 station x satellite x epoch
        # combinations: elevation and azimuth agree to a few thousandths of a
        # degree, range to 2.2e-4 relative (about 0.2-1.7 km depending on the
        # case's own range). All three are far below what a shape, sign, or
        # frame-mixing bug would produce (tens of degrees, or a wrong-sign
        # range).
        assert worst_elevation_deg < 0.05
        assert worst_azimuth_deg < 0.05
        assert worst_range_rel < 3e-4
