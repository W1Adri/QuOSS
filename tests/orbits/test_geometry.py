def _sso_700km(*, raan_rad: float, true_anomaly_rad: float) -> ClassicalElements:
    """Build a 700 km sun-synchronous orbit, the same numbers used throughout this repo.

    Same values as the worked example in ``perturbations.py``'s
    ``secular_rates_j2`` docstring, so a reader who has seen that example
    already knows this orbit.
    """
    return ClassicalElements.from_semi_major_axis(
        semi_major_axis_km=7078.137,
        eccentricity=0.001,
        inclination_rad=np.deg2rad(98.19),
        raan_rad=raan_rad,
        argp_rad=0.0,
        true_anomaly_rad=true_anomaly_rad,
    )


def _propagate_orbit(coe: ClassicalElements, *, span_s: float, n_samples: int) -> Trajectory:
    """Propagate over at most one period, in ``n_samples`` evenly spaced steps.

    Takes a sample *count* rather than a step size on purpose: capping the
    span at one period means the actual duration is whatever fraction of
    ``span_s`` the orbit allows, and :meth:`TimeGrid.uniform` rejects a
    ``step_s`` that does not divide that duration exactly. A sample count has
    no such constraint.
    """
    period_s = 2.0 * np.pi * np.sqrt(coe.semi_major_axis_km[0] ** 3 / EGM96_MU_KM3_S2)
    duration_s = min(span_s, period_s)
    grid = TimeGrid.uniform(epoch_jd=2460676.5, duration_s=duration_s, n=n_samples)
    return propagate(coe, grid, method=PropagationMethod.TWO_BODY)


def _up_unit_vector(latitude_rad: float, longitude_rad: float) -> np.ndarray:
    """Return the WGS-84 geodetic normal at a latitude/longitude, as a unit vector.

    The exact "up" direction :func:`~quoss.orbits.frames.enu_from_itrf` builds
    its basis from. Deliberately **not** ``geodetic_to_itrf(lat, lon, 0)``
    normalised: that point sits *on the ellipsoid*, and except at the poles or
    the equator its direction from the origin is not this normal — the same
    distinction ``docs/adr`` material on WGS-84 discusses for geodetic versus
    geocentric latitude. Adding a distance along the wrong one of the two
    would not land exactly at the zenith a test wants to construct.
    """
    return np.array(
        [
            np.cos(latitude_rad) * np.cos(longitude_rad),
            np.cos(latitude_rad) * np.sin(longitude_rad),
            np.sin(latitude_rad),
        ]
    )


def _trajectory_from_itrf_state(
    r_itrf_km: np.ndarray, v_itrf_km_s: np.ndarray, epoch_jd: float
) -> Trajectory:
    """Build a two-sample TEME Trajectory from one state stated in ITRF.

    The tests below want to reason about "the satellite is due east of the
    station" or "moving purely north" — statements about the *rotating*
    Earth-fixed frame. Building the state directly in ITRF and rotating it
    into TEME with :func:`~quoss.orbits.frames.itrf_to_teme_state` (the exact
    inverse of the rotation ``look_angles`` applies internally) keeps that
    geometry exact, rather than re-deriving the rotation by hand in every
    test. Two samples, not one, only because :class:`TimeGrid` requires at
    least two; every caller reads index 0 and ignores index 1.
    """
    epochs = np.array([epoch_jd, epoch_jd + 1.0 / 86_400.0])
    theta = gmst_rad(epochs)
    r_itrf = np.tile(r_itrf_km, (2, 1))
    v_itrf = np.tile(v_itrf_km_s, (2, 1))
    r_teme, v_teme = itrf_to_teme_state(r_itrf, v_itrf, theta)
    grid = TimeGrid.uniform(epoch_jd=epoch_jd, duration_s=1.0, n=2)
    return Trajectory(
        r_km=r_teme[np.newaxis, :, :],
        v_km_s=v_teme[np.newaxis, :, :],
        grid=grid,
        frame=Frame.TEME,
        method=PropagationMethod.TWO_BODY,
    )


